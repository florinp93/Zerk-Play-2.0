({String phrase, String label})? tagRo(String keyword) {
  final entry = tagPhrasesRo[keyword.toLowerCase()];
  if (entry == null) return null;
  final bar = entry.indexOf('|');
  if (bar >= 0) return (phrase: entry.substring(0, bar), label: entry.substring(bar + 1));
  final words = entry.split(' ');
  const prepositions = {'cu', 'despre', 'din', 'de', 'după', 'pe', 'pentru'};
  final rest = prepositions.contains(words.first) && words.length > 1 ? words.skip(1).join(' ') : entry;
  return (phrase: 'cele $entry', label: rest[0].toUpperCase() + rest.substring(1));
}
